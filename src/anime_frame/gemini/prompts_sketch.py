    "Match IMAGE 2's empty space and margins.\n"
    "CHARACTER CONSISTENCY -- CRITICAL FOR SEQUENCES: draw the character IDENTICALLY in "
    "every frame. Take the canonical look from the model sheet's MAIN FULL-BODY FRONT "
    "view and use that same look every single time. Every accessory the character has "
