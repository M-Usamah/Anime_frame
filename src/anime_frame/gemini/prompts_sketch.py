"""Gemini sketch-generation prompts."""

# Appended when a previously finished frame of the SAME sequence is supplied. Without
# it every frame is an independent read of the model sheet, so details that the sheet
# shows more than one way (e.g. a hat drawn on the head in one view and on the back in
# another) come out differently from frame to frame.
CONSISTENCY_REF = (
    "\nIMAGE 3 is the ANCHOR: an approved frame from THIS SAME sequence. Use IMAGE 3 "
    "ONLY to keep the character's SCALE and DESIGN identical across the sequence:\n"
    "- SCALE & SIZE: the same character height and on-screen size, and the same size for "
    "the head, hands and every accessory (a hat/cape the EXACT same size as in IMAGE 3). "
    "Do not zoom or rescale between frames.\n"
    "- DESIGN: the same hairstyle, outfit, accessory placement, body proportions, line "
    "weight and drawing style.\n"
    "DO NOT COPY THE ANCHOR'S POSE. This frame's pose comes ENTIRELY from IMAGE 2. These "
    "are CONSECUTIVE animation frames, so the pose is usually only SLIGHTLY different from "
    "the anchor -- and you MUST reproduce those small differences, never flatten them to "
    "match the anchor. Read IMAGE 2 carefully and copy its EXACT pose: the precise angle "
    "of each arm and leg, every hand position, the head tilt and the body lean shown in "
    "THIS rough. If IMAGE 2's arm/hand/head is even a little higher, lower or rotated "
    "versus the anchor, draw it exactly where IMAGE 2 shows it. The character keeps the "
    "anchor's LOOK and SIZE but takes THIS rough's exact pose -- so that when the frames "
    "play back, the motion genuinely moves."
)

# Option B: rough (gesture) + Canny edge map (structure) sent together.
ROUGH_CANNY_REF = (
    "\nOPTION B — TWO POSE GUIDES for this frame:\n"
    "IMAGE 2 is the ROUGH GESTURE SKETCH. Read IMAGE 2 for the EXACT pose nuance: hand "
    "shapes (fist vs open), joint angles, head tilt, body lean, foreshortening, and small "
    "frame-to-frame motion. IGNORE image 2's character identity.\n"
    "IMAGE 3 is the CANNY EDGE MAP of the SAME frame (white background, black silhouette "
    "edges). Use IMAGE 3 for FRAMING ONLY: where the figure sits in the frame, overall "
    "silhouette width/height, and limb placement. Match IMAGE 3's on-screen position and "
    "margins — do NOT re-center, zoom, crop, or rescale relative to IMAGE 3.\n"
    "Combine both: gesture, hands, and depth from IMAGE 2; framing and silhouette from IMAGE 3.\n"
    "CONSTRUCTION MARKS — IMAGE 2 may contain animator construction lines: circles at "
    "joints, axis lines, overlapping corrections, and stray strokes. These are NOT body "
    "parts. Do NOT turn a joint circle or overlapping sketch stroke into an extra arm, "
    "hand, leg or foot.\n"
    "LIMB COUNT — CRITICAL: draw EXACTLY two arms and two legs — no more. Each arm ends "
    "in ONE hand. Before finishing, verify: 2 shoulders, 2 upper arms, 2 forearms, "
    "2 hands, 2 thighs, 2 calves, 2 feet. Never add a phantom limb behind the body.\n"
    "FACE — copy IMAGE 2's facial expression exactly: surprised/shocked (wide eyes, small "
    "open mouth). Do NOT copy expression from IMAGE 1's model-sheet panels. Do NOT draw "
    "crying, tears, wailing, screaming, sweat drops, or the character's default comic "
    "distress face unless IMAGE 2 shows them.\n"
    "HANDS — count and match IMAGE 2: exactly TWO hands total. If IMAGE 2 shows open "
    "palms with spread fingers, draw open palms — not fists. Do NOT add a third hand.\n"
    "DEPTH & FORESHORTENING — CRITICAL: copy the 3D depth from IMAGE 2 exactly. The foot "
    "or hand closest to the camera must be drawn LARGER than the far foot/hand by the SAME "
    "ratio IMAGE 2 shows. Do NOT flatten both feet to equal size. Do NOT over-exaggerate "
    "one foot beyond what IMAGE 2 shows. Preserve which leg is near vs far."
)

# Anchor when rough+canny mode: images are target(1), rough(2), canny(3), anchor(4).
