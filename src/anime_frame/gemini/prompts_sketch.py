    "leans), how deeply the knees are bent and how high the legs are pulled up, and which "
    "way the body FACES (front, back or three-quarter). Do not straighten a reclined torso "
    "or lower raised knees.\n"
    "FRAMING -- CRITICAL FOR ANIMATION SEQUENCES: keep the character at the SAME "
    "position, the SAME scale and the SAME camera framing as in IMAGE 2. Do NOT re-centre "
